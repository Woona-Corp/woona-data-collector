private val russianMaximum = Regex("Максимум ([0-9]+) символов")
private val englishMaximum = Regex("Maximum ([0-9]+) characters")

fun questionnaireText(text: String, language: AppLanguage): String {
    if (language == AppLanguage.RUSSIAN) {
        englishMaximum.matchEntire(text)?.let { return "Максимум ${it.groupValues[1]} символов" }
        return russianValidation[text] ?: text
    }
    russianMaximum.matchEntire(text)?.let { return "Maximum ${it.groupValues[1]} characters" }
    return questionnaireEnglishLabels[text] ?: text
}
